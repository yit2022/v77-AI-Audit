const TABLES: Record<Locale, Dict> = { en, de, fr, pl, nl, es, it, sv };

export function t(locale: Locale, key: string): string {
  return TABLES[locale]?.[key] ?? TABLES.en[key] ?? key;
}

const LOCALE_SET = new Set<string>(LOCALES.map((l) => l.code));

export function isLocale(v: string | null | undefined): v is Locale {
  return Boolean(v && LOCALE_SET.has(v));
}

/** True when locale dict has a real (non-fallback-only) entry for key. */
export function hasTranslation(locale: Locale, key: string): boolean {
  return Boolean(TABLES[locale]?.[key]);
}

export function dictKeys(): string[] {
  return Object.keys(en);
}
